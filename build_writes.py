def load(p):
    return json.load(open(p, encoding="utf-8"))

def push_history(old_hist, date, close, chgPct, volRatio5, tags, newsNote, news, analysis):
    hist = [h for h in old_hist if h["date"] != date]
    hist.append({
        "date": date, "close": close, "chgPct": chgPct, "volRatio5": volRatio5,
        "tags": tags, "newsNote": newsNote, "news": news, "analysis": analysis
    })
    hist.sort(key=lambda h: h["date"])
    return hist[-7:]

def base_fields(calc, drop_vollots=False):
    f = {
        "date": calc["date"], "close": calc["close"], "prev": calc["prev"],
        "chg": calc["chg"], "chgPct": calc["chgPct"],
        "open": calc["open"], "high": calc["high"], "low": calc["low"],
        "volRatio5": calc["volRatio5"], "volRatio20": calc["volRatio20"],
        "ma": calc["ma"], "bias": calc["bias"], "arr": calc["arr"], "tags": calc["tags"],
        "hi20": calc["hi20"], "lo20": calc["lo20"], "hi60": calc["hi60"], "low5": calc["low5"],
        "dates": calc["dates"], "closes": calc["closes"],
    }
    if not drop_vollots:
        f["volLots"] = calc["volLots"]
    return f

